    manifest=json.loads(PIN.read_text(encoding='utf-8'))
    if sources() != manifest['sources']:
        raise ValueError('来源/注释/生成器改变，需重新人工核读绑定；不能只刷新哈希')
    results={}
    for name, rows in ACTORS.items():
        head=f'<!-- generated: build_personal_memory.py；不手改，不反写追踪 -->\n\n# {name}个人时间线（r249，截至099）\n\n'
        head+='来源：追踪/_tracking-state.json + 已接纳001—099正文 + 对应静态卡。完整哈希见本目录来源绑定.json。\n\n'
        head+='本页是逐章知情与行动的人工核读阅读视图，不是旧章七关审批证明。E编号用于回找章节，不表示本人知道事件摘要全部内容。未出场章节不自动推进其知情；当前来源不能解释的幕后状态留未知。\n\n'
        reader=head.replace('个人时间线','读者已见时间线')+'仅保留正文已展示/转述的行为；不从作者规划、静态未来卷设想补隐藏动机。\n\n'
        for r in rows:
            n=int(r['chapter']);p=next((BOOK/'正文').glob(f'第{n:03d}章*.md'))
            lines=p.read_text(encoding='utf-8-sig').splitlines()
