    prose = source.read_text(encoding="utf-8-sig")
    for old, new in replacements:
        assert prose.count(old) == 1, (number, old, prose.count(old))
        prose = prose.replace(old, new)
    target = root / source.name
    target.write_text(prose, encoding="utf-8")
