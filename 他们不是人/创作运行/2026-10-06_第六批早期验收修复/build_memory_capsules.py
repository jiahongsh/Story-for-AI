capsules = {}
for number in range(1, 51):
    if number == 11:
        continue
    item = rows[number]
    chapter_path = next((book / "正文").glob(f"第{number:03d}章_*.md"))
    original = chapter_path.read_text(encoding="utf-8-sig")
    summary = overrides.get(number, clean(item["summary"], 120))
    knowledge = clean(item["knowledge"], 120)
    if number in overrides:
        knowledge = knowledge_overrides[number]
    capsules[number] = {
        "chapter": number,
        "chapter_title": original.splitlines()[0].split(" ", 2)[-1],
        "story_time": story_time[number],
        "objective_fact": summary,
        "reader_knowledge": knowledge,
        "characters": actors[number],
        "source": chapter_path.relative_to(book).as_posix(),
        "source_sha256_at_audit": hashlib.sha256(chapter_path.read_bytes()).hexdigest(),
        "report": item["report"],
        "report_row": item["raw"],
        "audit_material_note_before_revision": clean(item["material"], 110),
    }

(work / "早期记忆来源包.json").write_text(json.dumps(capsules, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
