rows = {}
for report in reports:
    for line in report.read_text(encoding="utf-8-sig").splitlines():
        if not line.startswith("|") or line.startswith("|---"):
            continue
        columns = [cell.strip() for cell in line.split("|")]
        if len(columns) < 5:
            continue
        match = re.match(r"(?:\[)?0?(\d{1,3})(?:\])?(?:\([^)]*\))?\b", columns[1])
        if not match:
            match = re.match(r"\[(\d{1,3})\]", columns[1])
        if not match:
            continue
        number = int(match.group(1))
        if 1 <= number <= 50 and number not in rows:
            rows[number] = {"report": report.relative_to(book).as_posix(), "raw": line, "summary": columns[2], "knowledge": columns[3], "material": columns[5] if report == reports[0] and len(columns)>5 else (columns[4] if len(columns)>4 else "")}

assert len(rows) == 50, sorted(set(range(1,51))-set(rows))

def clean(value, limit=130):
    value = re.sub(r"\[[^]]+\]\([^)]+\)", "", value)
    value = re.sub(r"（\d+[^）]*）", "", value)
    value = value.replace("**", "").replace("`", "").strip(" ；。")
    value = re.sub(r"\s+", " ", value)
    return value[:limit].rstrip("；，。 ") + "。"

